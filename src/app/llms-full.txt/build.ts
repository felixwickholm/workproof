import { EVAL_RESULTS, EVAL_TESTS, PRINTED, UNIT_TESTS, VERIFIED_ON } from "@/app/for-judges/evidence";
import {
  AI_DOES,
  AI_NEVER,
  ARCHITECTURE_SUMMARY,
  AUDIENCES,
  BLIND_MISSES,
  BOOTH,
  BRIEF_QUOTES,
  CHECK_PATH,
  CODE_MAP,
  CRITERIA,
  DEMO_EVENT,
  ENTRY,
  ENTRY_POINTS,
  GUARDRAILS,
  KEY_FACTS,
  LIMITS,
  NAME,
  ONE_LINE,
  PAINS,
  PRIVACY,
  ROUTES,
  SUMMARY,
  SYNTHETIC,
  VERIFY_COMMANDS,
} from "@/app/for-judges/facts";

/** Markdown table cells cannot hold a raw pipe or a line break. */
const cell = (text: string) => text.replaceAll("|", "\\|").replace(/\s*\n\s*/g, " ");

const ticks = (items: readonly string[]) => items.map((i) => `\`${i}\``).join(", ");

/**
 * /llms-full.txt: the whole evidence page as one plain markdown file, for a reader that fetches one
 * address. Built from the same typed facts and measured figures as /for-judges and /llms.txt, so the
 * three never say different things. Routes are linked on `origin`, code paths on `repo`.
 */
export function buildLlmsFullTxt(origin: string, repo: string): string {
  const site = origin.replace(/\/$/, "");
  const code = repo.replace(/\/$/, "");
  const route = (path: string) => `[${path}](${site}${path})`;
  const routes = (paths: readonly string[]) => paths.map(route).join(", ");
  const lines = [
    `# ${NAME}`,
    "",
    `> ${SUMMARY}`,
    "",
    ONE_LINE,
    "",
    `- Live demo: ${site}`,
    `- Source code: ${code} (MIT licence)`,
    `- Entry: ${ENTRY.event} (${ENTRY.eventStart} to ${ENTRY.eventEnd}), ${ENTRY.challengeBy} challenge "${ENTRY.challenge}". First commit ${ENTRY.firstCommit}.`,
    ...ENTRY_POINTS.filter((e) => e.path !== "/llms-full.txt").map((e) => `- ${e.title}: ${site}${e.path}`),
    `- Numbers checked on ${VERIFIED_ON} with \`npm run evidence\`.`,
    `- Demo data only: ${DEMO_EVENT.employers} invented employers, ${DEMO_EVENT.tasks} challenges, ${DEMO_EVENT.proofs} pieces of work.`,
    "",
    "## Who it is for",
    "",
    ...AUDIENCES.map((a) => `- **${a.who}** (${a.mode}, ${route(a.path)}): ${a.does}`),
    "",
    "## Key facts",
    "",
    ...KEY_FACTS.map((fact) => `- ${fact}`),
    "",
    "## The challenge in the City of Espoo's words",
    "",
    ...BRIEF_QUOTES.flatMap((quote) => [`> ${quote}`, ""]),
    "## How WorkProof meets each judging criterion",
    "",
    "| Criterion | What we built | Where to see it | Where in code | Evidence |",
    "|---|---|---|---|---|",
    ...CRITERIA.map((c) => `| ${c.criterion} (${c.weight}) | ${cell(c.built)} | ${routes(c.routes)} | ${ticks(c.code)} | ${cell(c.evidence)} |`),
    "",
    "## How it answers each problem in the brief",
    "",
    "| Problem named in the brief | What WorkProof does | Where in code | Evidence |",
    "|---|---|---|---|",
    ...PAINS.map((p) => `| ${cell(p.pain)} | ${cell(p.built)} | ${ticks(p.code)} | ${cell(p.evidence)} |`),
    "",
    "## Shaped at the Espoo booth",
    "",
    BOOTH.intro,
    "",
    ...BOOTH.answers.map((a) => `- **${a.risk}** ${a.answer}`),
    "",
    "## What the AI does and never does",
    "",
    "Does:",
    "",
    ...AI_DOES.map((item) => `- ${item}`),
    "",
    "Never does:",
    "",
    ...AI_NEVER.map((item) => `- ${item}`),
    "",
    "## Guardrails",
    "",
    "| Rule | Enforced in | Checked by |",
    "|---|---|---|",
    ...GUARDRAILS.map((g) => `| ${cell(g.rule)} | ${ticks(g.enforced)} | ${ticks(g.checked)} |`),
    "",
    "## Architecture",
    "",
    ARCHITECTURE_SUMMARY,
    "",
    ...CODE_MAP.map((c) => `- [${c.path}](${code}/tree/main/${c.path}): ${c.what}`),
    "",
    "## Data and privacy",
    "",
    ...PRIVACY.map((item) => `- ${item}`),
    "",
    SYNTHETIC,
    "",
    `## Evidence, checked on ${VERIFIED_ON}`,
    "",
    `- \`${UNIT_TESTS.command}\`: ${UNIT_TESTS.passed} of ${UNIT_TESTS.tests} unit tests pass, in ${UNIT_TESTS.files} files.`,
    `- \`${EVAL_TESTS.command}\`: ${EVAL_TESTS.passed} of ${EVAL_TESTS.tests} eval tests pass, in ${EVAL_TESTS.files} files. The live-AI file is skipped without a key.`,
    `- Blind review, harder case set: the ${BLIND_MISSES.length} known misses are ${BLIND_MISSES.join(", ")}.`,
    "",
    "| Suite | What is counted | Result | File |",
    "|---|---|---|---|",
    ...EVAL_RESULTS.map((e) => `| ${e.suite} | ${cell(e.check)} | ${cell(e.result)} | \`${e.file}\` |`),
    "",
    "Every row `npm run eval` printed in that run:",
    "",
    "| Eval and check | Result |",
    "|---|---|",
    ...Object.entries(PRINTED).map(([check, result]) => `| ${cell(check)} | ${cell(result)} |`),
    "",
    "## How to verify",
    "",
    ...VERIFY_COMMANDS.map((c) => `- \`${c.command}\`: ${c.what}`),
    "",
    "In the running app:",
    "",
    ...CHECK_PATH.map((step) => `- ${route(step.path)}: ${step.what}`),
    "",
    "## Pages",
    "",
    ...ROUTES.map((r) => `- [${r.name}](${site}${r.path}): ${r.what}`),
    `- [How it works](${site}/how-it-works): the product in six plain steps`,
    `- [Short map](${site}/llms.txt): the same facts, shorter`,
    "",
    "## Limits",
    "",
    ...LIMITS.map((limit) => `- ${limit}`),
    "",
  ];
  return lines.join("\n");
}
